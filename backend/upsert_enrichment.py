"""
Upsert AI Enrichment outputs into Supabase.

Sources (generated by backend/ai_enrich.py):
- data/enrichment/candidate_ballot_briefs.json           → candidates.ai_ballot_brief
- data/enrichment/candidate_topic_stances.json           → candidates.ai_topic_stances
- data/enrichment/position_vectors.json                  → candidates.ai_position_vector
- data/enrichment/motion_explainers.json                 → motion_explainers (motion_key → data)
- data/enrichment/pairwise_briefs.json                   → pairwise_briefs (candidate_a_slug, candidate_b_slug, data)
- data/enrichment/qa_bank.json                           → qa_bank (slug, question, data)

Usage
  python backend/upsert_enrichment.py --all
  python backend/upsert_enrichment.py --candidates --motions --pairs --qa
  python backend/upsert_enrichment.py --dry-run --verbose

Requirements
- SUPABASE_PROJECT_URL and SUPABASE_SERVICE_ROLE_KEY in .env (service role is recommended)
"""

from __future__ import annotations

import os
import json
import logging
import re
from pathlib import Path
from typing import Dict, List, Any, Tuple

from dotenv import load_dotenv
from supabase import create_client, Client

from utils import setup_logging


ROOT_DIR = Path(__file__).resolve().parents[1]
DATA_DIR = ROOT_DIR / "data"
ENRICH_DIR = DATA_DIR / "enrichment"

BRIEFS_JSON = ENRICH_DIR / "candidate_ballot_briefs.json"
STANCES_JSON = ENRICH_DIR / "candidate_topic_stances.json"
VECTORS_JSON = ENRICH_DIR / "position_vectors.json"
EXPLAINERS_JSON = ENRICH_DIR / "motion_explainers.json"
PAIRWISE_JSON = ENRICH_DIR / "pairwise_briefs.json"
QA_JSON = ENRICH_DIR / "qa_bank.json"


def slugify(text: str) -> str:
    s = text.strip().lower()
    s = re.sub(r"[^a-z0-9]+", "-", s)
    s = re.sub(r"-+", "-", s).strip("-")
    return s[:80] if s else "item"


def load_json(path: Path) -> Any:
    with open(path, "r", encoding="utf-8") as f:
        return json.load(f)


def ensure_supabase() -> Client:
    load_dotenv()
    url = os.getenv("SUPABASE_PROJECT_URL")
    key = os.getenv("SUPABASE_SERVICE_ROLE_KEY") or os.getenv("SUPABASE_ANON_KEY")
    if not url:
        raise RuntimeError("SUPABASE_PROJECT_URL not set")
    if not key:
        raise RuntimeError("SUPABASE_SERVICE_ROLE_KEY or SUPABASE_ANON_KEY required (service role recommended)")
    return create_client(url, key)


def load_candidates_map(supabase: Client) -> Dict[str, str]:
    res = supabase.table("candidates").select("id,slug").execute()
    return {row["slug"]: row["id"] for row in res.data}


def upsert_candidates_jsonb(supabase: Client, cid_map: Dict[str, str], *, push_briefs: bool, push_stances: bool, push_vectors: bool, dry: bool, logger: logging.Logger) -> Tuple[int, int, int]:
    updated_briefs = updated_stances = updated_vectors = 0

    briefs = load_json(BRIEFS_JSON) if push_briefs and BRIEFS_JSON.exists() else {}
    stances = load_json(STANCES_JSON) if push_stances and STANCES_JSON.exists() else {}
    vectors = load_json(VECTORS_JSON) if push_vectors and VECTORS_JSON.exists() else {}

    # Iterate over union of slugs present in any file
    all_slugs = set(briefs.keys()) | set(stances.keys()) | set(vectors.keys())
    for slug in sorted(all_slugs):
        cid = cid_map.get(slug)
        if not cid:
            logger.warning(f"Candidate slug not found in DB: {slug}")
            continue
        payload: Dict[str, Any] = {}
        if push_briefs and slug in briefs:
            payload["ai_ballot_brief"] = briefs[slug]
        if push_stances and slug in stances:
            payload["ai_topic_stances"] = stances[slug]
        if push_vectors and slug in vectors:
            payload["ai_position_vector"] = vectors[slug]
        if not payload:
            continue
        if dry:
            logger.info(f"[DRY] candidates.update slug={slug} keys={list(payload.keys())}")
        else:
            supabase.table("candidates").update(payload).eq("id", cid).execute()
        updated_briefs += int("ai_ballot_brief" in payload)
        updated_stances += int("ai_topic_stances" in payload)
        updated_vectors += int("ai_position_vector" in payload)

    return updated_briefs, updated_stances, updated_vectors


def upsert_motion_explainers(supabase: Client, *, dry: bool, logger: logging.Logger) -> int:
    if not EXPLAINERS_JSON.exists():
        return 0
    explainers = load_json(EXPLAINERS_JSON)
    rows = [{"motion_key": k, "data": v} for k, v in explainers.items()]
    if not rows:
        return 0
    if dry:
        logger.info(f"[DRY] motion_explainers.upsert rows={len(rows)}")
        return len(rows)
    supabase.table("motion_explainers").upsert(rows, on_conflict="motion_key").execute()
    return len(rows)


def upsert_pairwise(supabase: Client, *, dry: bool, logger: logging.Logger) -> int:
    if not PAIRWISE_JSON.exists():
        return 0
    arr = load_json(PAIRWISE_JSON)
    rows = []
    for row in arr:
        a = row.get("candidate_a") or row.get("candidate_a_slug") or row.get("candidate_a_name")
        b = row.get("candidate_b") or row.get("candidate_b_slug") or row.get("candidate_b_name")
        data = row.get("data") or {}
        if not a or not b:
            continue
        rows.append({
            "candidate_a_slug": a,
            "candidate_b_slug": b,
            "data": data,
            "prompt_version": row.get("prompt_version"),
            "model_version": row.get("model_version"),
            "ai_model_used": row.get("ai_model_used"),
            "ai_response_tokens": row.get("ai_response_tokens"),
        })
    if not rows:
        return 0
    if dry:
        logger.info(f"[DRY] pairwise_briefs.upsert rows={len(rows)}")
        return len(rows)
    supabase.table("pairwise_briefs").upsert(rows, on_conflict="candidate_a_slug,candidate_b_slug").execute()
    return len(rows)


def upsert_qa(supabase: Client, *, dry: bool, logger: logging.Logger) -> int:
    if not QA_JSON.exists():
        return 0
    qa = load_json(QA_JSON)
    rows = []
    for question, data in qa.items():
        slug = slugify(question)
        rows.append({
            "slug": slug,
            "question": question,
            "data": data,
        })
    if not rows:
        return 0
    if dry:
        logger.info(f"[DRY] qa_bank.upsert rows={len(rows)}")
        return len(rows)
    supabase.table("qa_bank").upsert(rows, on_conflict="slug").execute()
    return len(rows)


def main() -> None:
    import argparse

    parser = argparse.ArgumentParser(description="Upsert AI Enrichment outputs to Supabase")
    parser.add_argument("--all", action="store_true", help="Push candidates, motions, pairs, qa")
    parser.add_argument("--candidates", action="store_true", help="Push candidate briefs/stances/vectors")
    parser.add_argument("--motions", action="store_true", help="Push motion explainers")
    parser.add_argument("--pairs", action="store_true", help="Push pairwise briefs")
    parser.add_argument("--qa", action="store_true", help="Push QA bank")
    parser.add_argument("--dry-run", action="store_true", help="Do not write to Supabase, just log actions")
    parser.add_argument("--verbose", action="store_true", help="Verbose logs")

    args = parser.parse_args()

    logger = setup_logging(DATA_DIR / "upsert_enrichment.log", "INFO")
    if args.verbose:
        import logging as _logging
        _logging.getLogger().setLevel(_logging.DEBUG)
        logger.debug("Verbose mode enabled")

    do_all = args.all or not (args.candidates or args.motions or args.pairs or args.qa)
    push_candidates = do_all or args.candidates
    push_motions = do_all or args.motions
    push_pairs = do_all or args.pairs
    push_qa = do_all or args.qa

    supabase = ensure_supabase()
    cid_map = load_candidates_map(supabase)

    logger.info("Starting upsert to Supabase...")
    total = {}

    if push_candidates:
        b, s, v = upsert_candidates_jsonb(
            supabase, cid_map,
            push_briefs=True, push_stances=True, push_vectors=True,
            dry=args.dry_run, logger=logger
        )
        total["candidates_briefs"] = b
        total["candidates_stances"] = s
        total["candidates_vectors"] = v

    if push_motions:
        m = upsert_motion_explainers(supabase, dry=args.dry_run, logger=logger)
        total["motion_explainers"] = m

    if push_pairs:
        p = upsert_pairwise(supabase, dry=args.dry_run, logger=logger)
        total["pairwise_briefs"] = p

    if push_qa:
        q = upsert_qa(supabase, dry=args.dry_run, logger=logger)
        total["qa_bank"] = q

    logger.info(f"Upsert complete: {total}")


if __name__ == "__main__":
    main()

